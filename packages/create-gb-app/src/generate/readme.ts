function features(stack: Stack): string[] {
  const selected: string[] = [stack.frontend, stack.backend];
  if ('api' in stack && stack.api !== 'none') selected.push(stack.api);
  if ('database' in stack && stack.database !== 'none') {
    selected.push(stack.database, stack.orm);
  }
  if (stack.auth !== 'none') selected.push(stack.auth);
  if (stack.payments !== 'none') selected.push(stack.payments);
  if (stack.addons.form !== 'none') selected.push(stack.addons.form);
  if (stack.addons.taskRunner === 'turborepo') selected.push('turborepo');
  selected.push(stack.addons.linting);
  return selected.map(
    (item) =>
      `- **${LABELS[item] ?? item}** — ${FEATURE_DESCRIPTIONS[item] ?? 'Included in the stack'}`
  );
}

function existingNotes(readme: string | undefined): string {
  if (!readme) return '';
  const body = readme
    .replace(/^# [^\n]*\n/, '')
    .replace(/^\s*Generated by create-gb-app\.\s*/, '')
    .trim();
  if (!body) return '';
  return body.startsWith('## ') ? body : `## Configuration notes\n\n${body}`;
}

function databaseSetup(
  stack: Stack,
  files: FileMap,
  scripts: Record<string, string>,
  run: string
): string {
  if (!('database' in stack) || stack.database === 'none') return '';
  const envPath = Object.keys(files).find((path) => path.endsWith('.env'));
  const commands = ['db:generate', 'db:push', 'db:migrate']
    .filter((name) => name in scripts)
    .map((name) => `${run} ${name}`);
  return [
    '## Database setup',
    '',
    `Set the database connection in \`${envPath ?? '.env'}\` before running schema commands.`,
    '',
    ...(commands.length ? ['```bash', ...commands, '```'] : []),
  ].join('\n');
}

export function generateReadme(
  stack: Stack,
  ctx: GenerateContext,
  files: FileMap,
  pkg: PackageJsonShape
): string {
  const manager = PACKAGE_MANAGER_METADATA[ctx.packageManager];
  const notes = existingNotes(files['README.md']);
  const hasDatabaseNotes = /^## Database setup\b/im.test(notes);
  const envPaths = Object.keys(files).filter((path) =>
    /(^|\/)\.env(\.example|\.local)?$/.test(path)
  );
  const scripts = Object.keys(pkg.scripts).map((name) => {
    const description = SCRIPT_DESCRIPTIONS[name] ?? 'Run the project task';
    return `- \`${manager.run} ${name}\` — ${description}.`;
  });
  const sections = [
    `# ${ctx.projectName}`,
    'Created with create-gb-app, a TypeScript starter configured for this stack.',
    `## Features\n\n${features(stack).join('\n')}`,
    `## Getting started\n\nInstall dependencies from the project root:\n\n\`\`\`bash\n${manager.install}\n\`\`\``,
  ];

  if (!hasDatabaseNotes) {
    const setup = databaseSetup(stack, files, pkg.scripts, manager.run);
    if (setup) sections.push(setup);
  }
  if (notes) sections.push(notes);

  if (stack.backend === 'convex' && pkg.scripts['convex:dev']) {
    sections.push(
      `## Start developing\n\nConnect Convex in one terminal with \`${manager.run} convex:dev\`, then run \`${manager.run} dev\` in another.`
    );
  } else {
    sections.push(
      `## Start developing\n\n\`\`\`bash\n${manager.run} dev\n\`\`\``
    );
  }

  if (envPaths.length > 0) {
    sections.push(
      `## Environment configuration\n\nReview the generated ${envPaths.map((path) => `\`${path}\``).join(', ')} file${envPaths.length === 1 ? '' : 's'} and replace development placeholders before deployment.`
    );
  }

  if (stack.auth === 'better-auth') {
    const authEnvPath = envPaths.find((path) =>
      files[path].includes('BETTER_AUTH_URL=')
    );
    if (authEnvPath) {
      const defaultOrigin = files[authEnvPath].match(
        /BETTER_AUTH_URL="([^"]+)"/
      )?.[1];
      sections.push(
        `## Authentication setup\n\nIn \`${authEnvPath}\`, set \`BETTER_AUTH_URL\` to the actual served origin of the authentication server (scheme, hostname, and port). The generated development default is \`${defaultOrigin}\`. Update it when using another hostname or port, and use the HTTPS origin of each preview or production deployment. The built-in backend serves authentication from the same origin as the web app. Restart the server after changing these values.\n\nReplace \`BETTER_AUTH_SECRET\` with a randomly generated secret of at least 32 characters. Keep it private and stable across server restarts; configure it and the database connection variables from that file in the deployment environment before starting the application.`
      );
    }
  }

  sections.push(`## Available scripts\n\n${scripts.join('\n')}`);
  return `${sections.join('\n\n')}\n`;
}
