import type { HonoStack } from '#/types/stack';

import type { EmitCtx } from '../../types/generate';
import { DEPENDENCY_VERSIONS } from '../dependency-versions';
import { setFile } from '../files';
import { emitPolar } from './polar';
import {
  emitServerWorkspace,
  SERVER_LISTEN_PORT,
  SERVER_URL,
  WEB_ORIGIN,
  writeServerManifest,
} from './server-workspace';
import { emitStripe } from './stripe';

export function emitHono(ctx: EmitCtx): void {
  if (ctx.stack.backend !== 'hono') {
    throw new Error('emitHono requires hono');
  }
  const stack = ctx.stack;
  emitServerWorkspace(ctx, {
    nodeNext: false,
    tsconfig: {
      compilerOptions: {
        outDir: 'dist',
        rootDir: 'src',
        types: ['node'],
      },
      include: ['src'],
    },
    emit: (context, dep) => {
      emitServer(context, stack, dep);
      emitWeb(context, stack, dep);
      emitChosenPayments(context, stack);
      setFile(
        context.files,
        'README.md',
        `# ${context.projectName}

Generated by create-gb-app.

The server listens with [@hono/node-server](https://hono.dev/docs/getting-started/nodejs).
See the Hono Node guide for the Node.js adapter.
`
      );
    },
  });
}

function emitChosenPayments(ctx: EmitCtx, stack: HonoStack): void {
  switch (stack.payments) {
    case 'none':
      break;
    case 'stripe':
      emitStripe(ctx);
      break;
    case 'polar':
      emitPolar(ctx);
      break;
    default: {
      const _exhaustive: never = stack.payments;
      throw new Error(`unhandled payments: ${_exhaustive}`);
    }
  }
}

function emitServer(ctx: EmitCtx, stack: HonoStack, dep: string): void {
  const dependencies: Record<string, string> = {
    '@hono/node-server': DEPENDENCY_VERSIONS['@hono/node-server'],
    hono: DEPENDENCY_VERSIONS['hono'],
  };
  const devDependencies: Record<string, string> = {
    '@repo/typescript-config': dep,
    '@types/node': DEPENDENCY_VERSIONS['@types/node'],
    tsx: DEPENDENCY_VERSIONS['tsx'],
    typescript: DEPENDENCY_VERSIONS['typescript'],
  };

  if (stack.database !== 'none' && stack.orm === 'prisma') {
    dependencies['@prisma/client'] = DEPENDENCY_VERSIONS['@prisma/client'];
    devDependencies.prisma = DEPENDENCY_VERSIONS['prisma'];
  }
  if (stack.database !== 'none' && stack.orm === 'drizzle') {
    dependencies['drizzle-orm'] = DEPENDENCY_VERSIONS['drizzle-orm'];
    devDependencies['drizzle-kit'] = DEPENDENCY_VERSIONS['drizzle-kit'];
  }
  if (stack.auth === 'better-auth') {
    dependencies['better-auth'] = DEPENDENCY_VERSIONS['better-auth'];
  }
  if (stack.auth === 'clerk') {
    dependencies['@hono/clerk-auth'] = DEPENDENCY_VERSIONS['@hono/clerk-auth'];
  }
  if (stack.database !== 'none' && stack.api === 'orpc') {
    dependencies['@orpc/openapi'] = DEPENDENCY_VERSIONS['@orpc/openapi'];
    dependencies['@orpc/server'] = DEPENDENCY_VERSIONS['@orpc/server'];
    dependencies['@repo/contract'] = dep;
  }
  if (stack.database !== 'none' && stack.api === 'trpc') {
    dependencies['@hono/trpc-server'] =
      DEPENDENCY_VERSIONS['@hono/trpc-server'];
    dependencies['@repo/contract'] = dep;
    dependencies['@trpc/server'] = DEPENDENCY_VERSIONS['@trpc/server'];
  }

  writeServerManifest(ctx, {
    scripts: {
      dev: 'tsx watch src/index.ts',
      start: 'tsx src/index.ts',
      build: 'tsc',
    },
    dependencies,
    devDependencies,
  });

  if (stack.auth === 'better-auth' && stack.database !== 'none') {
    emitServerAuth(ctx, stack);
  }

  setFile(ctx.files, 'apps/server/src/index.ts', serverEntry(stack));
}

function authProvider(stack: HonoStack): string {
  if (stack.database === 'mysql') {
    return 'mysql';
  }
  if (stack.database === 'sqlite') {
    return 'sqlite';
  }
  return 'postgresql';
}

function emitServerAuth(ctx: EmitCtx, stack: HonoStack): void {
  const provider = authProvider(stack);
  const source =
    stack.orm === 'drizzle'
      ? `import { betterAuth } from "better-auth";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import { db } from "./db";

export const auth = betterAuth({
  database: drizzleAdapter(db, { provider: "${stack.database === 'mysql' ? 'mysql' : stack.database === 'sqlite' ? 'sqlite' : 'pg'}" }),
  emailAndPassword: { enabled: true },
  trustedOrigins: ["${WEB_ORIGIN}"],
  baseURL: "${SERVER_URL}",
});
`
      : `import { betterAuth } from "better-auth";
import { prismaAdapter } from "better-auth/adapters/prisma";
import { prisma } from "./db";

export const auth = betterAuth({
  database: prismaAdapter(prisma, { provider: "${provider}" }),
  emailAndPassword: { enabled: true },
  trustedOrigins: ["${WEB_ORIGIN}"],
  baseURL: "${SERVER_URL}",
});
`;
  setFile(ctx.files, 'apps/server/src/auth.ts', source);
}

function serverEntry(stack: HonoStack): string {
  const imports = [
    `import { serve } from "@hono/node-server";`,
    `import { Hono } from "hono";`,
    `import { cors } from "hono/cors";`,
  ];
  if (stack.auth === 'clerk') {
    imports.push(
      `import { clerkMiddleware, getAuth } from "@hono/clerk-auth";`
    );
  }
  if (stack.auth === 'better-auth' && stack.database !== 'none') {
    imports.push(`import { auth } from "./auth";`);
  }
  if (stack.database !== 'none' && stack.api === 'orpc') {
    imports.push(`import { OpenAPIHandler } from "@orpc/openapi/fetch";`);
    imports.push(`import { router } from "./orpc";`);
  }
  if (stack.database !== 'none' && stack.api === 'trpc') {
    imports.push(`import { trpcServer } from "@hono/trpc-server";`);
    imports.push(`import { appRouter } from "@repo/contract";`);
  }
  if (stack.database !== 'none' && stack.api === 'none') {
    imports.push(
      `import { createNote, listNotes, removeNote, updateNote } from "./notes";`
    );
    imports.push(`import { noteInputSchema } from "@repo/validation";`);
  }
  if (stack.database !== 'none' && stack.api === 'trpc') {
    imports.push(`import * as notes from "./notes";`);
  }

  const lines = [
    ...imports,
    '',
    `export const app = new Hono<{ Variables: { userId: string | null } }>();`,
    '',
    `app.use("*", cors({ origin: "${WEB_ORIGIN}", credentials: true }));`,
  ];

  if (stack.auth === 'clerk') {
    lines.push(`app.use("*", clerkMiddleware());`);
    lines.push(`app.use("*", async (c, next) => {`);
    lines.push(`  c.set("userId", getAuth(c)?.userId ?? null);`);
    lines.push(`  await next();`);
    lines.push(`});`);
  } else if (stack.auth === 'better-auth' && stack.database !== 'none') {
    lines.push(`app.use("*", async (c, next) => {`);
    lines.push(
      `  const session = await auth.api.getSession({ headers: c.req.raw.headers });`
    );
    lines.push(`  c.set("userId", session?.user.id ?? null);`);
    lines.push(`  await next();`);
    lines.push(`});`);
    lines.push(
      `app.on(["POST", "GET"], "/api/auth/*", (c) => auth.handler(c.req.raw));`
    );
  } else {
    lines.push(`app.use("*", async (c, next) => {`);
    lines.push(`  c.set("userId", null);`);
    lines.push(`  await next();`);
    lines.push(`});`);
  }

  lines.push('');
  lines.push(`app.get("/health", (c) => c.json({ ok: true }));`);

  if (stack.database !== 'none' && stack.api === 'none') {
    lines.push(restRoutes(stack.auth !== 'none'));
  }
  if (stack.database !== 'none' && stack.api === 'orpc') {
    lines.push(`const handler = new OpenAPIHandler(router);`);
    lines.push(`app.all("/api/*", async (c) => {`);
    lines.push(
      `  const { matched, response } = await handler.handle(c.req.raw, {`
    );
    lines.push(`    prefix: "/api",`);
    lines.push(
      `    context: { headers: c.req.raw.headers, userId: c.get("userId") },`
    );
    lines.push(`  });`);
    lines.push(`  if (matched) {`);
    lines.push(`    return c.newResponse(response.body, response);`);
    lines.push(`  }`);
    lines.push(`  return c.notFound();`);
    lines.push(`});`);
  }
  if (stack.database !== 'none' && stack.api === 'trpc') {
    lines.push(`app.use(`);
    lines.push(`  "/trpc/*",`);
    lines.push(`  trpcServer({`);
    lines.push(`    router: appRouter,`);
    lines.push(`    createContext: (_opts, c) => ({`);
    lines.push(`      userId: c.get("userId"),`);
    lines.push(`      notes: {`);
    lines.push(`        list: notes.listNotes,`);
    lines.push(`        create: notes.createNote,`);
    lines.push(`        update: notes.updateNote,`);
    lines.push(`        remove: notes.removeNote,`);
    lines.push(`      },`);
    lines.push(`    }),`);
    lines.push(`  }),`);
    lines.push(`);`);
  }

  lines.push('');
  lines.push(`serve({ fetch: app.fetch, port: ${SERVER_LISTEN_PORT} });`);
  lines.push('');
  return lines.join('\n');
}

function restRoutes(authed: boolean): string {
  const deny = authed
    ? `  if (!c.get("userId")) {\n    return c.json({ error: "UNAUTHORIZED" }, 401);\n  }\n  `
    : '';
  return `
app.get("/notes", async (c) => {
  ${deny}return c.json(await listNotes(c.get("userId")));
});

app.post("/notes", async (c) => {
  ${deny}const parsed = noteInputSchema.safeParse(await c.req.json());
  if (!parsed.success) {
    return c.json({ error: "VALIDATION_ERROR", issues: parsed.error.issues }, 400);
  }
  return c.json(await createNote(c.get("userId"), parsed.data));
});

app.patch("/notes/:id", async (c) => {
  ${deny}const parsed = noteInputSchema.safeParse(await c.req.json());
  if (!parsed.success) {
    return c.json({ error: "VALIDATION_ERROR", issues: parsed.error.issues }, 400);
  }
  return c.json(await updateNote(c.get("userId"), { id: c.req.param("id"), ...parsed.data }));
});

app.delete("/notes/:id", async (c) => {
  ${deny}return c.json(await removeNote(c.get("userId"), c.req.param("id")));
});
`;
}

function emitWeb(ctx: EmitCtx, stack: HonoStack, dep: string): void {
  switch (stack.frontend) {
    case 'next':
      emitNextWeb(ctx, stack, dep);
      break;
    case 'tanstack-start':
      emitStartWeb(ctx, stack, dep);
      break;
    default: {
      const _exhaustive: never = stack.frontend;
      throw new Error(`unhandled frontend: ${_exhaustive}`);
    }
  }
}

function webDependencies(
  stack: HonoStack,
  dep: string
): Record<string, string> {
  const dependencies: Record<string, string> = {
    '@repo/ui': dep,
    react: DEPENDENCY_VERSIONS['react'],
    'react-dom': DEPENDENCY_VERSIONS['react-dom'],
  };
  if (stack.auth === 'better-auth') {
    dependencies['better-auth'] = DEPENDENCY_VERSIONS['better-auth'];
  }
  if (stack.auth === 'clerk' && stack.frontend === 'next') {
    dependencies['@clerk/nextjs'] = DEPENDENCY_VERSIONS['@clerk/nextjs'];
  }
  if (stack.auth === 'clerk' && stack.frontend === 'tanstack-start') {
    dependencies['@clerk/tanstack-react-start'] =
      DEPENDENCY_VERSIONS['@clerk/tanstack-react-start'];
  }
  if (stack.database !== 'none' && stack.api === 'orpc') {
    dependencies['@orpc/client'] = DEPENDENCY_VERSIONS['@orpc/client'];
    dependencies['@orpc/contract'] = DEPENDENCY_VERSIONS['@orpc/contract'];
    dependencies['@orpc/openapi'] = DEPENDENCY_VERSIONS['@orpc/openapi'];
    dependencies['@repo/contract'] = dep;
    dependencies['@tanstack/react-query'] =
      DEPENDENCY_VERSIONS['@tanstack/react-query'];
  }
  if (stack.database !== 'none' && stack.api === 'trpc') {
    dependencies['@repo/contract'] = dep;
    dependencies['@tanstack/react-query'] =
      DEPENDENCY_VERSIONS['@tanstack/react-query'];
    dependencies['@trpc/client'] = DEPENDENCY_VERSIONS['@trpc/client'];
    dependencies['@trpc/react-query'] =
      DEPENDENCY_VERSIONS['@trpc/react-query'];
  }
  return dependencies;
}

