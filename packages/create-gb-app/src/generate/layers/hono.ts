const SERVER_URL = 'http://localhost:3333';
const WEB_ORIGIN = 'http://localhost:3000';

function proto(ctx: EmitCtx): string {
  return workspaceProtocol(ctx.packageManager);
}

export function emitHono(ctx: EmitCtx): void {
  if (ctx.stack.backend !== 'hono') {
    throw new Error('emitHono requires hono');
  }

  const stack = ctx.stack;
  const dep = proto(ctx);
  ctx.pkg.private = true;
  ctx.pkg.scripts.dev = 'turbo dev';
  ctx.pkg.scripts.build = 'turbo build';
  ctx.pkg.scripts.lint = 'turbo lint';
  ctx.pkg.devDependencies.turbo = DEPENDENCY_VERSIONS['turbo'];
  ctx.pkg.devDependencies.typescript = DEPENDENCY_VERSIONS['typescript'];
  ctx.pkg.workspaces = ['apps/*', 'packages/*'];

  setFile(
    ctx.files,
    'turbo.json',
    JSON.stringify(
      {
        $schema: 'https://turborepo.dev/schema.json',
        tasks: {
          build: {
            dependsOn: ['^build'],
            outputs: [
              'dist/**',
              '.next/**',
              '!.next/cache/**',
              '.output/**',
              '.vinxi/**',
            ],
          },
          dev: { cache: false, persistent: true },
          lint: { dependsOn: ['^lint'] },
        },
      },
      null,
      2
    )
  );

  setFile(
    ctx.files,
    '.gitignore',
    `node_modules
.turbo
.next
.output
.vinxi
dist
.env
*.log
`
  );

  emitTypescriptConfig(ctx);
  if (stack.database !== 'none') {
    emitPostgres(ctx);
    switch (stack.orm) {
      case 'prisma':
        emitPrisma(ctx);
        break;
      case 'drizzle':
        emitDrizzle(ctx);
        break;
      case 'none':
        throw new Error('orm none requires database none');
      default: {
        const _exhaustive: never = stack.orm;
        throw new Error(`unhandled orm: ${_exhaustive}`);
      }
    }
    emitDbSetup(ctx);
  }

  if (stack.api === 'orpc') {
    emitOrpcContract(ctx, dep);
  } else if (stack.api === 'trpc') {
    emitTrpcContract(ctx, dep);
  }

  emitUiPackage(ctx, dep);
  emitServer(ctx, stack, dep);
  emitWeb(ctx, stack, dep);
  emitChosenLinter(ctx, stack);
  emitChosenPayments(ctx, stack);

  setFile(
    ctx.files,
    'README.md',
    `# ${ctx.projectName}

Generated by create-gb-app.

The server listens with [@hono/node-server](https://hono.dev/docs/getting-started/nodejs).
See the Hono Node guide for the Node.js adapter.
`
  );
}

function emitChosenLinter(ctx: EmitCtx, stack: HonoStack): void {
  switch (stack.addons.linting) {
    case 'eslint':
      emitEslint(ctx);
      break;
    case 'biome':
      emitBiome(ctx);
      break;
    case 'oxlint':
      emitOxlint(ctx);
      break;
    default: {
      const _exhaustive: never = stack.addons.linting;
      throw new Error(`unhandled linter: ${_exhaustive}`);
    }
  }
}

function emitChosenPayments(ctx: EmitCtx, stack: HonoStack): void {
  switch (stack.payments) {
    case 'none':
      break;
    case 'stripe':
      emitStripe(ctx);
      break;
    case 'polar':
      emitPolar(ctx);
      break;
    default: {
      const _exhaustive: never = stack.payments;
      throw new Error(`unhandled payments: ${_exhaustive}`);
    }
  }
}

